"""Export the pinned D5h current decision without promoting any source eligibility."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

from scripts.normalize_crcl import ROOT
from scripts.review_crcl_registration import ACQUISITION, REPORT

REVIEW_SHA = "56698d5707f62b2349c5865bc6f98d73f236f493c38d3192477f4ce2909fdce9"
OUTPUT = "apps/web/src/features/analysis-readiness/registration.json"
MANIFEST = "apps/web/src/features/analysis-readiness/registration-manifest.ts"


def project(review: dict[str, Any]) -> dict[str, Any]:
    encoded = json.dumps(review, indent=2, sort_keys=True) + "\n"
    if hashlib.sha256(encoded.encode()).hexdigest() != REVIEW_SHA:
        raise ValueError("D5h current evidence changed; new review required")
    if (
        review["operatingMargin"] is not None
        or review["publishedMetricCount"] != 0
        or review["candidateBatch"]["status"] != "blocked"
        or review["candidateBatch"]["batchId"] is not None
    ):
        raise ValueError("D5h cannot publish financial eligibility or a metric")
    return review


def generated(root: Path = ROOT) -> dict[str, str]:
    raw = (root / REPORT).read_bytes()
    if hashlib.sha256(raw).hexdigest() != REVIEW_SHA:
        raise ValueError("Pinned D5h review changed")
    review = project(json.loads(raw))
    if hashlib.sha256((root / ACQUISITION).read_bytes()).hexdigest() != review["acquisitionSha256"]:
        raise ValueError("D5h acquisition lineage changed")
    preparation = (root / "docs/research/crcl-current-preparation-2026-10-13.json").read_bytes()
    if (
        hashlib.sha256(preparation).hexdigest()
        != "a2a10425e1ccc6bc969f186a0e6de8b2fd714ab7a3a6afca7a18bb546aee0f62"
    ):
        raise ValueError("D5h blocked preparation lineage changed")
    snapshot = json.dumps(review, indent=2, sort_keys=True) + "\n"
    digest = hashlib.sha256(snapshot.encode()).hexdigest()
    return {
        OUTPUT: snapshot,
        MANIFEST: "// Generated by scripts.export_crcl_registration.\n"
        f'export const registrationSha256 = "{digest}";\n',
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generated().items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != text:
                raise ValueError("D5h export differs: " + path)
        else:
            target.write_text(text)


if __name__ == "__main__":
    main()
