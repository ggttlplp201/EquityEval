"""Export the pinned D5f current decision without promoting any source eligibility."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

from scripts.normalize_crcl import ROOT
from scripts.review_crcl_leadership import ACQUISITION, FACTS_ROSTER, REPORT

REVIEW_SHA = "34d2f906550867c3dcd155c8c07e60a94387884c491ae73dc714b8dc209354e5"
OUTPUT = "apps/web/src/features/analysis-readiness/leadership.json"
MANIFEST = "apps/web/src/features/analysis-readiness/leadership-manifest.ts"


def project(review: dict[str, Any]) -> dict[str, Any]:
    encoded = json.dumps(review, indent=2, sort_keys=True) + "\n"
    if hashlib.sha256(encoded.encode()).hexdigest() != REVIEW_SHA:
        raise ValueError("D5f current evidence changed; new review required")
    if (
        review["operatingMargin"] is not None
        or review["publishedMetricCount"] != 0
        or review["candidateBatch"]["status"] != "blocked"
        or review["candidateBatch"]["batchId"] is not None
    ):
        raise ValueError("D5f cannot publish financial eligibility or a metric")
    return review


def generated(root: Path = ROOT) -> dict[str, str]:
    raw = (root / REPORT).read_bytes()
    if hashlib.sha256(raw).hexdigest() != REVIEW_SHA:
        raise ValueError("Pinned D5f review changed")
    review = project(json.loads(raw))
    if hashlib.sha256((root / ACQUISITION).read_bytes()).hexdigest() != review["acquisitionSha256"]:
        raise ValueError("D5f acquisition lineage changed")
    if (
        hashlib.sha256((root / FACTS_ROSTER).read_bytes()).hexdigest()
        != review["factsRosterSha256"]
    ):
        raise ValueError("D5f retained Facts roster lineage changed")
    snapshot = json.dumps(review, indent=2, sort_keys=True) + "\n"
    digest = hashlib.sha256(snapshot.encode()).hexdigest()
    return {
        OUTPUT: snapshot,
        MANIFEST: "// Generated by scripts.export_crcl_leadership.\n"
        f'export const leadershipSha256 = "{digest}";\n',
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generated().items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != text:
                raise ValueError("D5f export differs: " + path)
        else:
            target.write_text(text)


if __name__ == "__main__":
    main()
