"""Export the pinned D5d exhibits decision without promoting any source eligibility."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

from scripts.normalize_crcl import ROOT
from scripts.review_crcl_exhibits import ACQUISITION, REPORT

REVIEW_SHA = "786bf9dc9e71dec48fc00c4977134b3e7b3d2137920f582ba86ae8069c48a7c7"
OUTPUT = "apps/web/src/features/analysis-readiness/exhibits.json"
MANIFEST = "apps/web/src/features/analysis-readiness/exhibits-manifest.ts"


def project(review: dict[str, Any]) -> dict[str, Any]:
    encoded = json.dumps(review, indent=2, sort_keys=True) + "\n"
    if hashlib.sha256(encoded.encode()).hexdigest() != REVIEW_SHA:
        raise ValueError("D5d exhibits evidence changed; new review required")
    if (
        review["operatingMargin"] is not None
        or review["publishedMetricCount"] != 0
        or review["historicalStatus"] != "blocked"
        or review["currentStatus"] != "blocked"
    ):
        raise ValueError("D5d cannot publish financial eligibility or a metric")
    return review


def generated(root: Path = ROOT) -> dict[str, str]:
    raw = (root / REPORT).read_bytes()
    if hashlib.sha256(raw).hexdigest() != REVIEW_SHA:
        raise ValueError("Pinned D5d review changed")
    review = project(json.loads(raw))
    if hashlib.sha256((root / ACQUISITION).read_bytes()).hexdigest() != review["acquisitionSha256"]:
        raise ValueError("D5d acquisition lineage changed")
    snapshot = json.dumps(review, indent=2, sort_keys=True) + "\n"
    digest = hashlib.sha256(snapshot.encode()).hexdigest()
    return {
        OUTPUT: snapshot,
        MANIFEST: "// Generated by scripts.export_crcl_exhibits.\n"
        f'export const exhibitsSha256 = "{digest}";\n',
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generated().items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != text:
                raise ValueError("D5d export differs: " + path)
        else:
            target.write_text(text)


if __name__ == "__main__":
    main()
