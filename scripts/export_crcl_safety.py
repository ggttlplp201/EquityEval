"""Export the pinned D5c safety decision without promoting any source eligibility."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

from scripts.normalize_crcl import ROOT
from scripts.review_crcl_safety import ACQUISITION, REPORT

REVIEW_SHA = "eebf5017428f29ef8fd3f8b8fbc42798d0cb224bb1f4ed84337995859ae6a8f6"
OUTPUT = "apps/web/src/features/analysis-readiness/safety.json"
MANIFEST = "apps/web/src/features/analysis-readiness/safety-manifest.ts"


def project(review: dict[str, Any]) -> dict[str, Any]:
    encoded = json.dumps(review, indent=2, sort_keys=True) + "\n"
    if hashlib.sha256(encoded.encode()).hexdigest() != REVIEW_SHA:
        raise ValueError("D5c safety evidence changed; new review required")
    if (
        review["operatingMargin"] is not None
        or review["publishedMetricCount"] != 0
        or review["historicalDecision"]["status"] != "blocked"
        or review["retrospectiveDecision"]["status"] != "incomplete"
    ):
        raise ValueError("D5c cannot publish financial eligibility or a metric")
    return review


def generated(root: Path = ROOT) -> dict[str, str]:
    raw = (root / REPORT).read_bytes()
    if hashlib.sha256(raw).hexdigest() != REVIEW_SHA:
        raise ValueError("Pinned D5c review changed")
    review = project(json.loads(raw))
    if hashlib.sha256((root / ACQUISITION).read_bytes()).hexdigest() != review["acquisitionSha256"]:
        raise ValueError("D5c acquisition lineage changed")
    snapshot = json.dumps(review, indent=2, sort_keys=True) + "\n"
    digest = hashlib.sha256(snapshot.encode()).hexdigest()
    return {
        OUTPUT: snapshot,
        MANIFEST: "// Generated by scripts.export_crcl_safety.\n"
        f'export const safetySha256 = "{digest}";\n',
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generated().items():
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != text:
                raise ValueError("D5c export differs: " + path)
        else:
            target.write_text(text)


if __name__ == "__main__":
    main()
